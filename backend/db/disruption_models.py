"""
SQLAlchemy ORM Models for Module 5: Disruption Management and Timetable Rescheduling Engine.
Supports PostgreSQL and SQLite database engines.
"""

from datetime import datetime
from typing import List, Optional
from sqlalchemy import (
    Column,
    String,
    Integer,
    Boolean,
    Float,
    DateTime,
    ForeignKey,
    Text
)
from sqlalchemy.orm import declarative_base, relationship

Base = declarative_base()


class DisruptionModel(Base):
    """Stores reported campus scheduling disruptions."""
    __tablename__ = "disruptions"

    id = Column(String(50), primary_key=True, index=True)
    title = Column(String(200), nullable=True)
    description = Column(Text, nullable=False)
    dataset_id = Column(String(50), default="cit-public-v1")
    raw_json = Column(Text, nullable=False)
    changes_json = Column(Text, nullable=True)  # JSON array of disruption changes
    status = Column(String(30), default="reported")  # reported, analyzing, proposal_generated, approved, rejected
    reported_by = Column(String(100), default="admin")
    reported_at = Column(DateTime, default=datetime.utcnow)
    impact_summary_json = Column(Text, nullable=True)
    sessions_moved = Column(Integer, default=0)
    applied_at = Column(DateTime, nullable=True)
    applied_by = Column(String(100), nullable=True)

    proposals = relationship("ReschedulingProposalModel", back_populates="disruption", cascade="all, delete-orphan")


class ReschedulingProposalModel(Base):
    """Stores candidate rescheduling solutions generated by CP-SAT."""
    __tablename__ = "rescheduling_proposals"

    id = Column(String(50), primary_key=True, index=True)
    disruption_id = Column(String(50), ForeignKey("disruptions.id", ondelete="CASCADE"), nullable=False)
    baseline_timetable_id = Column(String(50), nullable=False, default="baseline")
    target_timetable_version = Column(String(50), nullable=False)
    status = Column(String(30), default="proposed")  # proposed, approved, rejected
    solver_status = Column(String(30), nullable=False)  # OPTIMAL, FEASIBLE, INFEASIBLE
    solve_time_seconds = Column(Float, default=0.0)
    sessions_moved = Column(Integer, default=0)
    time_changed = Column(Integer, default=0)
    room_only_changed = Column(Integer, default=0)
    unchanged_sessions = Column(Integer, default=0)
    hard_violations_count = Column(Integer, default=0)
    hard_violations_json = Column(Text, nullable=True)
    soft_penalty = Column(Integer, default=0)
    diff_json = Column(Text, nullable=True)
    created_by = Column(String(100), default="admin")
    created_at = Column(DateTime, default=datetime.utcnow)
    decided_by = Column(String(100), nullable=True)
    decided_at = Column(DateTime, nullable=True)
    decision_reason = Column(Text, nullable=True)

    disruption = relationship("DisruptionModel", back_populates="proposals")
    assignments = relationship("ProposalAssignmentModel", back_populates="proposal", cascade="all, delete-orphan")


class ProposalAssignmentModel(Base):
    """Stores detailed session-level assignment changes in a proposal."""
    __tablename__ = "rescheduling_proposal_assignments"

    id = Column(Integer, primary_key=True, autoincrement=True)
    proposal_id = Column(String(50), ForeignKey("rescheduling_proposals.id", ondelete="CASCADE"), nullable=False)
    session_id = Column(String(50), nullable=False)
    course_id = Column(String(50), nullable=True)
    faculty_id = Column(String(50), nullable=True)
    groups_json = Column(Text, nullable=True)
    original_day = Column(String(10), nullable=True)
    original_start_period = Column(Integer, nullable=True)
    original_room_id = Column(String(50), nullable=True)
    proposed_day = Column(String(10), nullable=True)
    proposed_start_period = Column(Integer, nullable=True)
    proposed_room_id = Column(String(50), nullable=True)
    is_moved = Column(Boolean, default=False)
    change_type = Column(String(50), default="unchanged")  # unchanged, time_and_room, time_only, room_only, new_session, removed_session
    change_reason = Column(Text, nullable=True)

    proposal = relationship("ReschedulingProposalModel", back_populates="assignments")


class ReschedulingAuditLogModel(Base):
    """Immutable audit trail for all disruption and rescheduling events."""
    __tablename__ = "rescheduling_audit_logs"

    id = Column(Integer, primary_key=True, autoincrement=True)
    proposal_id = Column(String(50), nullable=True)
    disruption_id = Column(String(50), nullable=True)
    user_id = Column(String(50), nullable=False)
    user_role = Column(String(50), nullable=False)
    action = Column(String(100), nullable=False)
    details_json = Column(Text, nullable=True)
    timestamp = Column(DateTime, default=datetime.utcnow)
